// Doctor Profile QR — port of the web Settings → Profile QR page
// (Setting/SettingProfileQR/profileQR.jsx). One permanent QR that opens the
// doctor's public profile:
//   GET /api/auth/me                     profile details shown on the card
//   GET /api/qr/doctors/:doctorId/codes  { profileQrUrl, profileQrCode }
// The clinic walk-in QR + LED display live on the separate QR Code screen
// (DoctorProfileQrScreen), like the web's /qrcode page.
import React, { useCallback, useEffect, useState } from 'react';
import { ActivityIndicator, Image, Linking, Platform, Pressable, ScrollView, Share, View } from 'react-native';
import RNFS from 'react-native-fs';
import LinearGradient from 'react-native-linear-gradient';
import Text from '../../../../components/TranslatedText';
import AppIcon from '../icons/AppIcon';
import { useToast } from '../../../../components/common/ToastProvider';
import { createDoctorStyles } from '../theme';
import { CLINICIAN_GRADIENT } from '../../../../theme/palette';
import axiosInstance from '../../../../axiosConfig';
import { PUBLIC_WEB_APP_URL } from '../../../../config';
import { getStoredDoctorUser, pickFirst } from '../api/doctorAppointments';

const HUMAELI_LOGO = require('../../../../image/HumaeliIcon.png');

// The dev server builds links on its own frontend origin (localhost), which
// no patient's phone can open — share / open those on the public web app.
const publicUrl = (url) => {
  const value = String(url || '');
  const match = /^https?:\/\/(?:localhost|127\.0\.0\.1|10\.0\.2\.2)(?::\d+)?(\/.*)?$/i.exec(value);
  return match ? `${PUBLIC_WEB_APP_URL.replace(/\/+$/, '')}${match[1] || ''}` : value;
};

const textOf = (value) => {
  if (Array.isArray(value)) return value.filter((v) => typeof v === 'string' || typeof v === 'number').join(', ');
  return typeof value === 'string' || typeof value === 'number' ? String(value).trim() : '';
};

// Same patient-facing fields as the web's publicDoctorProfile().
const toPublicProfile = (data = {}, fallback = {}) => {
  const src = data.user || data.profile || data.doctor || data;
  const read = (...keys) => keys.map((k) => textOf(src[k]) || textOf(fallback[k])).find(Boolean) || '';
  return {
    name: read('full_name', 'fullName', 'name'),
    speciality: read('speciality', 'specialization', 'primary_specialties'),
    email: read('email', 'email_address'),
    phone: read('contact_number', 'phoneNumber', 'phone_number', 'phone', 'mobile', 'contactNumber'),
    qualification: read('qualification', 'medical_degree'),
    clinic: read('clinic_name', 'primary_hospital', 'hospital_name'),
  };
};

export default function DoctorProfileCardQrScreen({ onBack }) {
  const { showToast } = useToast();
  const [profile, setProfile] = useState(null);
  const [qrSrc, setQrSrc] = useState('');
  const [profileLink, setProfileLink] = useState('');
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState('');
  const [qrError, setQrError] = useState(false);

  const load = useCallback(async () => {
    setLoading(true);
    setError('');
    setQrError(false);
    try {
      const stored = (await getStoredDoctorUser()) || {};
      const user = stored.user || stored.data?.user || stored;
      const doctorId = pickFirst(user.doctor_id, user.doctorId, user.id, user._id, user.user_id, user.userId);
      if (!doctorId) throw new Error('Doctor ID not found. Please sign in again.');
      const me = await axiosInstance.get('/api/auth/me');
      const details = toPublicProfile(me.data?.data || me.data || {}, user);
      if (!details.name) throw new Error('Please complete your doctor profile before generating a QR.');
      setProfile(details);
      const qr = await axiosInstance.get(`/api/qr/doctors/${encodeURIComponent(doctorId)}/codes`);
      const codes = qr.data?.data || qr.data || {};
      setProfileLink(publicUrl(codes.profileQrUrl));
      setQrSrc(codes.profileQrCode || '');
    } catch (err) {
      setError(err?.response?.data?.message || err?.message || 'Unable to load doctor profile.');
    } finally {
      setLoading(false);
    }
  }, []);

  useEffect(() => { load(); }, [load]);

  const openProfile = () => {
    if (!profileLink) return;
    Linking.openURL(profileLink).catch(() => showToast('Could not open the profile link'));
  };

  const shareProfile = () => {
    if (!profileLink) return;
    Share.share({
      title: profile?.name,
      message: `Scan or open this link to view ${profile?.name}'s profile.\n${profileLink}`,
    }).catch(() => {});
  };

  // profileQrCode is a PNG data URL generated by the backend.
  const downloadQr = async () => {
    const base64 = String(qrSrc || '').split(',')[1];
    if (!base64) return;
    const safeName = String(profile?.name || 'doctor').replace(/[^a-z0-9]+/gi, '-').toLowerCase();
    const dir = Platform.OS === 'android' ? RNFS.DownloadDirectoryPath : RNFS.DocumentDirectoryPath;
    try {
      await RNFS.writeFile(`${dir}/${safeName}-profile-qr.png`, base64, 'base64');
      if (Platform.OS === 'android') RNFS.scanFile(`${dir}/${safeName}-profile-qr.png`).catch(() => {});
      showToast(Platform.OS === 'android' ? 'QR saved to Downloads' : 'QR saved');
    } catch (err) {
      showToast('Could not save QR. Please share the link instead.');
    }
  };

  return (
    <View style={s.screen}>
      <View style={s.header}>
        <Pressable onPress={onBack} style={s.backButton} hitSlop={8}>
          <AppIcon name="chevron-left" size={22} color="#1F2937" strokeWidth={2.4} />
        </Pressable>
        <View style={s.flex}>
          <Text style={s.title}>Profile QR</Text>
          <Text style={s.subtitle}>Your permanent doctor profile QR</Text>
        </View>
      </View>

      <ScrollView contentContainerStyle={s.content} showsVerticalScrollIndicator={false}>
        {loading ? (
          <View style={s.stateBox}>
            <ActivityIndicator color="#0D9488" />
            <Text style={s.stateText}>Loading doctor profile QR...</Text>
          </View>
        ) : error ? (
          <View style={s.stateBox}>
            <AppIcon name="warning" size={26} color="#D92D20" />
            <Text style={s.errorText}>{error}</Text>
            <Pressable onPress={load} style={s.retry}><Text style={s.retryText}>Retry</Text></Pressable>
          </View>
        ) : (
          <>
            <View style={s.card}>
              <View style={s.info}>
                <Image source={HUMAELI_LOGO} style={s.logo} />
                <View style={s.flex}>
                  <Text translate={false} style={s.name} numberOfLines={2}>{profile.name}</Text>
                  {!!profile.speciality && <Text style={s.speciality} numberOfLines={2}>{profile.speciality}</Text>}
                </View>
              </View>
              <View style={s.rows}>
                <InfoRow icon="mail" label="Email" value={profile.email || 'Not provided'} />
                <InfoRow icon="phone" label="Phone" value={profile.phone || 'Not provided'} />
                {!!profile.qualification && <InfoRow icon="briefcase" label="Qualification" value={profile.qualification} />}
                {!!profile.clinic && <InfoRow icon="home" label="Clinic" value={profile.clinic} />}
              </View>

              <View style={s.qrBlock}>
                <View style={s.qrFrame}>
                  {qrError || !qrSrc ? (
                    <View style={s.qrMissing}>
                      <Text style={s.qrMissingText}>QR image could not load.</Text>
                      <Pressable onPress={load} hitSlop={6}><Text style={s.link}>Retry</Text></Pressable>
                    </View>
                  ) : (
                    <Image source={{ uri: qrSrc }} style={s.qrImage} resizeMode="contain" onError={() => setQrError(true)} />
                  )}
                </View>
                <Text style={s.scanText}>Scan for Doctor Profile</Text>
                <Pressable onPress={openProfile} disabled={!profileLink} hitSlop={6} style={s.viewProfile}>
                  <AppIcon name="eye" size={15} color="#0D9488" strokeWidth={2.2} />
                  <Text style={s.link}>View profile</Text>
                </Pressable>
              </View>
            </View>

            <Pressable onPress={downloadQr} disabled={!qrSrc} style={s.primaryWrap}>
              <LinearGradient colors={CLINICIAN_GRADIENT} start={{ x: 0, y: 0 }} end={{ x: 1, y: 0 }} style={s.primary}>
                <AppIcon name="download" size={16} color="#FFF" strokeWidth={2.2} />
                <Text style={s.primaryText}>Download QR</Text>
              </LinearGradient>
            </Pressable>
            <Pressable onPress={shareProfile} disabled={!profileLink} style={s.outline}>
              <AppIcon name="send" size={15} color="#0F766E" strokeWidth={2.2} />
              <Text style={s.outlineText}>Share profile link</Text>
            </Pressable>

            <View style={s.note}>
              <AppIcon name="info" size={15} color="#0F766E" strokeWidth={2.2} />
              <Text style={s.noteText}>
                Your permanent doctor profile QR shows your latest profile and available clinics. Clinic changes do not require a new profile QR.
              </Text>
            </View>
          </>
        )}
      </ScrollView>
    </View>
  );
}

function InfoRow({ icon, label, value }) {
  return (
    <View style={s.row}>
      <AppIcon name={icon} size={15} color="#0D9488" strokeWidth={2} />
      <Text style={s.rowLabel}>{label}</Text>
      <Text translate={false} style={s.rowValue} numberOfLines={2}>{value}</Text>
    </View>
  );
}

